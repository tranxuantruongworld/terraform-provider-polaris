package provider

import (
	"context"
	"fmt"

	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/booldefault"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/types"
	"github.com/tranxuantruongworld/terraform-provider-polaris/internal/client"
)

var (
	_ resource.Resource                = &PrincipalResource{}
	_ resource.ResourceWithConfigure   = &PrincipalResource{}
	_ resource.ResourceWithImportState = &PrincipalResource{}
)

func NewPrincipalResource() resource.Resource {
	return &PrincipalResource{}
}

type PrincipalResource struct {
	client *client.Client
}

type PrincipalResourceModel struct {
	Name                       types.String `tfsdk:"name"`
	ClientID                   types.String `tfsdk:"client_id"`
	ClientSecret               types.String `tfsdk:"client_secret"`
	CredentialRotationRequired types.Bool   `tfsdk:"credential_rotation_required"`
	Properties                 types.Map    `tfsdk:"properties"`
	CreateTimestamp            types.Int64  `tfsdk:"create_timestamp"`
	LastUpdateTimestamp        types.Int64  `tfsdk:"last_update_timestamp"`
	EntityVersion              types.Int64  `tfsdk:"entity_version"`
}

func (r *PrincipalResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_principal"
}

func (r *PrincipalResource) Schema(ctx context.Context, req resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		Description: "Manages an Apache Polaris principal identity and its client credentials.",
		Attributes: map[string]schema.Attribute{
			"name": schema.StringAttribute{
				Description: "The unique username of the Polaris principal.",
				Required:    true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.RequiresReplace(),
				},
			},
			"client_id": schema.StringAttribute{
				Description: "OAuth2 client ID generated by Polaris for this principal.",
				Computed:    true,
			},
			"client_secret": schema.StringAttribute{
				Description: "OAuth2 client secret generated by Polaris upon principal creation.",
				Computed:    true,
				Sensitive:   true,
			},
			"credential_rotation_required": schema.BoolAttribute{
				Description: "Whether initial credentials must be immediately rotated upon first use.",
				Optional:    true,
				Computed:    true,
				Default:     booldefault.StaticBool(false),
			},
			"properties": schema.MapAttribute{
				Description: "Custom properties associated with this principal.",
				Optional:    true,
				Computed:    true,
				ElementType: types.StringType,
			},
			"create_timestamp": schema.Int64Attribute{
				Description: "Creation epoch timestamp in milliseconds.",
				Computed:    true,
			},
			"last_update_timestamp": schema.Int64Attribute{
				Description: "Last update epoch timestamp in milliseconds.",
				Computed:    true,
			},
			"entity_version": schema.Int64Attribute{
				Description: "Current entity version counter for optimistic concurrency.",
				Computed:    true,
			},
		},
	}
}

func (r *PrincipalResource) Configure(ctx context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}

	c, ok := req.ProviderData.(*client.Client)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Resource Configure Type",
			fmt.Sprintf("Expected *client.Client, got: %T. Please report this issue to provider maintainers.", req.ProviderData),
		)
		return
	}

	r.client = c
}

func (r *PrincipalResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var data PrincipalResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	props := make(map[string]string)
	if !data.Properties.IsNull() && !data.Properties.IsUnknown() {
		resp.Diagnostics.Append(data.Properties.ElementsAs(ctx, &props, false)...)
		if resp.Diagnostics.HasError() {
			return
		}
	}

	createReq := client.CreatePrincipalRequest{
		Principal: client.Principal{
			Name:       data.Name.ValueString(),
			Properties: props,
		},
		CredentialRotationRequired: data.CredentialRotationRequired.ValueBool(),
	}

	created, err := r.client.CreatePrincipal(ctx, createReq)
	if err != nil {
		resp.Diagnostics.AddError("Error Creating Polaris Principal", fmt.Sprintf("Could not create principal %s: %s", data.Name.ValueString(), err.Error()))
		return
	}

	data.Name = types.StringValue(created.Principal.Name)
	data.ClientID = types.StringValue(created.Credentials.ClientID)
	data.ClientSecret = types.StringValue(created.Credentials.ClientSecret)
	data.CreateTimestamp = types.Int64Value(created.Principal.CreateTimestamp)
	data.LastUpdateTimestamp = types.Int64Value(created.Principal.LastUpdateTimestamp)
	data.EntityVersion = types.Int64Value(created.Principal.EntityVersion)

	if len(created.Principal.Properties) > 0 {
		propsMap, _ := types.MapValueFrom(ctx, types.StringType, created.Principal.Properties)
		data.Properties = propsMap
	} else {
		data.Properties = types.MapNull(types.StringType)
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *PrincipalResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var data PrincipalResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	principal, err := r.client.GetPrincipal(ctx, data.Name.ValueString())
	if err != nil {
		if client.IsNotFound(err) {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Error Reading Polaris Principal", fmt.Sprintf("Could not read principal %s: %s", data.Name.ValueString(), err.Error()))
		return
	}

	data.Name = types.StringValue(principal.Name)
	if principal.ClientID != "" {
		data.ClientID = types.StringValue(principal.ClientID)
	}
	data.CreateTimestamp = types.Int64Value(principal.CreateTimestamp)
	data.LastUpdateTimestamp = types.Int64Value(principal.LastUpdateTimestamp)
	data.EntityVersion = types.Int64Value(principal.EntityVersion)

	if len(principal.Properties) > 0 {
		propsMap, _ := types.MapValueFrom(ctx, types.StringType, principal.Properties)
		data.Properties = propsMap
	} else {
		data.Properties = types.MapNull(types.StringType)
	}

	// ClientSecret remains untouched from state since Polaris does not return it on GET

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *PrincipalResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var data PrincipalResourceModel

	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	props := make(map[string]string)
	if !data.Properties.IsNull() && !data.Properties.IsUnknown() {
		resp.Diagnostics.Append(data.Properties.ElementsAs(ctx, &props, false)...)
		if resp.Diagnostics.HasError() {
			return
		}
	}

	updateReq := client.UpdatePrincipalRequest{
		CurrentEntityVersion: data.EntityVersion.ValueInt64(),
		Properties:           props,
	}

	updated, err := r.client.UpdatePrincipal(ctx, data.Name.ValueString(), updateReq)
	if err != nil {
		resp.Diagnostics.AddError("Error Updating Polaris Principal", fmt.Sprintf("Could not update principal %s: %s", data.Name.ValueString(), err.Error()))
		return
	}

	data.Name = types.StringValue(updated.Name)
	if updated.ClientID != "" {
		data.ClientID = types.StringValue(updated.ClientID)
	}
	data.CreateTimestamp = types.Int64Value(updated.CreateTimestamp)
	data.LastUpdateTimestamp = types.Int64Value(updated.LastUpdateTimestamp)
	data.EntityVersion = types.Int64Value(updated.EntityVersion)

	if len(updated.Properties) > 0 {
		propsMap, _ := types.MapValueFrom(ctx, types.StringType, updated.Properties)
		data.Properties = propsMap
	} else {
		data.Properties = types.MapNull(types.StringType)
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *PrincipalResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var data PrincipalResourceModel

	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	err := r.client.DeletePrincipal(ctx, data.Name.ValueString())
	if err != nil && !client.IsNotFound(err) {
		resp.Diagnostics.AddError("Error Deleting Polaris Principal", fmt.Sprintf("Could not delete principal %s: %s", data.Name.ValueString(), err.Error()))
		return
	}
}

func (r *PrincipalResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	resource.ImportStatePassthroughID(ctx, path.Root("name"), req, resp)
}
